package com.neoterux.easyfact.testing

import com.neoterux.easyfact.invoicing.result.Outcome
import com.neoterux.easyfact.invoicing.signing.FixedIdSource
import com.neoterux.easyfact.invoicing.signing.IssuerNameFormats
import com.neoterux.easyfact.invoicing.signing.Rfc2253Jdk
import com.neoterux.easyfact.invoicing.signing.SigningIdentity
import com.neoterux.easyfact.invoicing.signing.XadesBesSigner
import com.neoterux.easyfact.invoicing.xml.CanonicalDocument
import com.neoterux.easyfact.invoicing.xml.CanonicalEmitter
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths
import java.security.KeyStore
import java.security.SecureRandom
import java.time.OffsetDateTime
import java.time.ZoneOffset
import java.time.temporal.ChronoUnit

/**
 * Mints the assets of the on-device golden-byte test (NFR-07, D-23): for each case a PKCS#12, and
 * for each case that can sign, the exact bytes the JVM produces for the same inputs. A device that
 * loads the same store and signs the same document with the same identifiers and signing time must
 * reproduce those bytes; any difference is a platform difference worth knowing about.
 *
 * Everything is written under one output directory chosen by the caller, which is always under a
 * build directory. Nothing here is committed: a generated store holds a private key and the signed
 * documents embed its certificate. The keys are synthetic and are derived from a fixed seed per case
 * (see [seededRandom]) so the expected documents can be regenerated byte for byte; a key that
 * anybody can re-derive protects nothing, and nothing ever trusts it.
 *
 * The document is built here and again by the device test with the same few emitter calls, because
 * [CanonicalDocument] has no public constructor from bytes by design. The device test asserts its own
 * unsigned octets equal [UNSIGNED_FILE], so a drift between the two builders fails loudly and names
 * itself instead of surfacing as a signature mismatch.
 */
object GoldenAssetGenerator {

    const val MANIFEST_FILE = "golden/manifest.properties"
    const val UNSIGNED_FILE = "golden/unsigned.xml"

    /** The signing time every case uses, at the SRI's fixed UTC-05:00 offset. */
    val SIGNING_TIME: OffsetDateTime = OffsetDateTime.of(2026, 10, 27, 12, 0, 0, 0, ZoneOffset.ofHours(-5))

    /** The first of the eight consecutive identifiers the signer draws. */
    const val FIRST_ID = 100000

    private const val WRONG_PASSWORD = "not-the-password"

    /** First level at which the AES-256 / HmacSHA256 PKCS#12 is expected to open. 34 is the lowest level measured to open it. */
    private const val AES_PKCS12_OPENS_FROM_API = 34

    /** What the device is expected to do with a case. */
    enum class Expectation {
        /** The store opens and signing reproduces the expected bytes. */
        SIGNS,

        /** The store must refuse to open, with an exception rather than a crash. */
        REJECTS_PASSWORD,
    }

    /** One case of the matrix. [encoding] and [shape] name what is being exercised. */
    class GoldenCase(
        val id: String,
        val description: String,
        val shape: IssuerShape,
        val encoding: Pkcs12Encoding,
        val expectation: Expectation,
        /** The password written to the manifest for the device to use; deliberately wrong for [Expectation.REJECTS_PASSWORD]. */
        val devicePassword: String,
        /**
         * The lowest Android API level at which a [Expectation.SIGNS] case is expected to open. Below it the
         * device must refuse the store (an `IOException` naming the MAC or key failure) and the test asserts
         * that refusal, so a platform that starts opening the file fails the test and the expectation gets
         * revisited. `0` means the case is expected to open on every level.
         */
        val opensFromApi: Int = 0,
        /**
         * The correct password for the store, required for [Expectation.REJECTS_PASSWORD] cases and `null`
         * for [Expectation.SIGNS] cases. The device opens the store with it first, so a refusal with
         * [devicePassword] afterwards can only be the password and never an unreadable store.
         */
        val controlPassword: String? = null,
    )

    /**
     * The cases research named as the ones that can differ between ART and the JVM. The issuer cases
     * use the legacy PKCS#12 encoding so that a device which cannot open the modern encoding still
     * answers the issuer-name question; the two encodings are separate cases of their own.
     *
     * The rejection cases are two, on purpose. `wrong-password` uses the legacy encoding, which opens on
     * every measured level (API 31, 34 and 37), so a refusal there can only be the password: the same
     * case on the AES encoding passed vacuously on API 31, where the file cannot be read at all.
     * `wrong-password-modern-aes` keeps the AES encoding covered from the level at which it opens.
     * Each rejection case carries a [GoldenCase.controlPassword] that the device must open the store with
     * before the wrong password is tried.
     */
    val CASES: List<GoldenCase> = listOf(
        GoldenCase(
            "issuer-oid-utf8",
            "Issuer carries 2.5.4.97 as UTF8String",
            IssuerShape.ORGANIZATION_IDENTIFIER_UTF8,
            Pkcs12Encoding.LEGACY_PBE,
            Expectation.SIGNS,
            SyntheticCertificates.DEFAULT_PASSWORD,
        ),
        GoldenCase(
            "issuer-oid-printable",
            "Issuer carries 2.5.4.97 as PrintableString",
            IssuerShape.ORGANIZATION_IDENTIFIER_PRINTABLE,
            Pkcs12Encoding.LEGACY_PBE,
            Expectation.SIGNS,
            SyntheticCertificates.DEFAULT_PASSWORD,
        ),
        GoldenCase(
            "issuer-non-ascii",
            "Issuer common name contains non-ASCII letters",
            IssuerShape.NON_ASCII,
            Pkcs12Encoding.LEGACY_PBE,
            Expectation.SIGNS,
            SyntheticCertificates.DEFAULT_PASSWORD,
        ),
        GoldenCase(
            "p12-legacy-pbe",
            "PKCS#12 protected with PBEWithSHA1AndDESede, RC2-40 and an HmacPBESHA1 MAC",
            IssuerShape.PLAIN,
            Pkcs12Encoding.LEGACY_PBE,
            Expectation.SIGNS,
            SyntheticCertificates.DEFAULT_PASSWORD,
        ),
        GoldenCase(
            "p12-modern-aes",
            "PKCS#12 protected with PBES2 AES-256 and an HmacSHA256 MAC",
            IssuerShape.PLAIN,
            Pkcs12Encoding.MODERN_AES,
            Expectation.SIGNS,
            SyntheticCertificates.DEFAULT_PASSWORD,
            // Measured: API 31 refuses ("error constructing MAC ... No installed provider supports this
            // key: PKCS12Key"); API 34 and 37 open it. API 32 and 33 are UNMEASURED and are assumed to
            // refuse like 31, so an emulator on either level that opens the file fails the test.
            opensFromApi = AES_PKCS12_OPENS_FROM_API,
        ),
        GoldenCase(
            "wrong-password",
            "A valid legacy-encoded PKCS#12 opened with the wrong password",
            IssuerShape.PLAIN,
            Pkcs12Encoding.LEGACY_PBE,
            Expectation.REJECTS_PASSWORD,
            WRONG_PASSWORD,
            opensFromApi = 0,
            controlPassword = SyntheticCertificates.DEFAULT_PASSWORD,
        ),
        GoldenCase(
            "wrong-password-modern-aes",
            "A valid AES-256 PKCS#12 opened with the wrong password",
            IssuerShape.PLAIN,
            Pkcs12Encoding.MODERN_AES,
            Expectation.REJECTS_PASSWORD,
            WRONG_PASSWORD,
            opensFromApi = AES_PKCS12_OPENS_FROM_API,
            controlPassword = SyntheticCertificates.DEFAULT_PASSWORD,
        ),
    )

    @JvmStatic
    fun main(args: Array<String>) {
        require(args.size == 1) { "usage: GoldenAssetGenerator <output-directory>" }
        val written = generate(Paths.get(args[0]))
        println("GoldenAssetGenerator: wrote $written files for ${CASES.size} cases into ${args[0]}")
    }

    /** Writes every asset into [outputDir] and returns the number of files written. */
    fun generate(outputDir: Path): Int {
        val goldenDir = outputDir.resolve("golden")
        Files.createDirectories(goldenDir)
        var files = 0

        val unsigned = unsignedDocument()
        Files.write(outputDir.resolve(UNSIGNED_FILE), unsigned.octets())
        files++

        val manifest = linkedMapOf<String, String>()
        manifest["cases"] = CASES.joinToString(",") { it.id }
        manifest["signingTime"] = SIGNING_TIME.toString()
        manifest["firstId"] = FIRST_ID.toString()
        manifest["unsigned"] = "unsigned.xml"

        val validFrom = SIGNING_TIME.toInstant().minus(30, ChronoUnit.DAYS)
        val validUntil = SIGNING_TIME.toInstant().plus(365, ChronoUnit.DAYS)

        for (case in CASES) {
            val identity = SyntheticCertificates.rsa2048(case.shape, validFrom, validUntil, seededRandom(case.id))
            val store = SyntheticCertificates.pkcs12(identity, SyntheticCertificates.DEFAULT_PASSWORD.toCharArray(), case.encoding)
            val storeName = "${case.id}.p12"
            Files.write(goldenDir.resolve(storeName), store)
            files++

            val prefix = "case.${case.id}"
            manifest["$prefix.description"] = case.description
            manifest["$prefix.p12"] = storeName
            manifest["$prefix.password"] = case.devicePassword
            manifest["$prefix.encoding"] = case.encoding.name
            manifest["$prefix.expect"] = case.expectation.name
            manifest["$prefix.opensFromApi"] = case.opensFromApi.toString()
            case.controlPassword?.let { manifest["$prefix.controlPassword"] = it }
            for ((formatName, format) in IssuerNameFormats.ALL) {
                manifest["$prefix.issuer.$formatName"] = format.render(identity.certificate)
            }

            if (case.expectation == Expectation.SIGNS) {
                // The JVM's expected output is produced from the identity as the store hands it back,
                // not from the in-memory object, so both sides sign what a PKCS#12 round trip yields.
                val loaded = load(store, SyntheticCertificates.DEFAULT_PASSWORD.toCharArray())
                val signer = XadesBesSigner(FixedIdSource(FIRST_ID), Rfc2253Jdk) { SIGNING_TIME }
                val signed = when (val outcome = signer.sign(unsigned, loaded)) {
                    is Outcome.Ok -> outcome.value.octets()
                    is Outcome.Err -> error("case ${case.id} did not sign on the JVM: ${outcome.error}")
                }
                val signedName = "${case.id}.expected-signed.xml"
                Files.write(goldenDir.resolve(signedName), signed)
                files++
                manifest["$prefix.expectedSigned"] = signedName
            }
        }

        Files.write(outputDir.resolve(MANIFEST_FILE), renderManifest(manifest).toByteArray(Charsets.US_ASCII))
        files++
        return files
    }

    /** The unsigned document the device must rebuild with the same emitter calls. */
    fun unsignedDocument(): CanonicalDocument = CanonicalEmitter()
        .open("factura", mapOf("id" to "comprobante", "version" to "1.1.0"))
        .open("infoTributaria")
        .open("razonSocial").text("Test Emisor S.A. & Cia Ñandú").close()
        .close()
        .close()
        .document()

    private fun load(store: ByteArray, password: CharArray): SigningIdentity {
        val keyStore = KeyStore.getInstance("PKCS12").apply { load(store.inputStream(), password) }
        val alias = keyStore.aliases().nextElement()
        val key = keyStore.getKey(alias, password) as java.security.PrivateKey
        val certificate = keyStore.getCertificate(alias) as java.security.cert.X509Certificate
        return SigningIdentity(key, certificate)
    }

    /**
     * A deterministic generator seeded from the case identifier. `SHA1PRNG` is used on purpose: it is
     * the JDK generator whose output is fully determined by its seed when seeded before first use.
     * Only ever for synthetic keys that nothing trusts.
     */
    private fun seededRandom(caseId: String): SecureRandom =
        SecureRandom.getInstance("SHA1PRNG").apply { setSeed("easyfact-golden-$caseId".toByteArray(Charsets.UTF_8)) }

    /**
     * Renders [entries] as a `java.util.Properties` file that is pure ASCII, with one entry per line and
     * no timestamp comment (the library writer adds one, which would make two generations differ).
     * Non-ASCII characters become `\uXXXX` escapes, which `Properties.load` reads back on the JVM and ART.
     */
    private fun renderManifest(entries: Map<String, String>): String {
        val out = StringBuilder()
        for ((key, value) in entries) {
            out.append(escape(key, isKey = true)).append('=').append(escape(value, isKey = false)).append('\n')
        }
        return out.toString()
    }

    private fun escape(text: String, isKey: Boolean): String {
        val out = StringBuilder(text.length)
        for ((index, c) in text.withIndex()) {
            when {
                c == '\\' -> out.append("\\\\")
                c == '\n' -> out.append("\\n")
                c == '\r' -> out.append("\\r")
                c == '\t' -> out.append("\\t")
                c == '=' || c == ':' || c == '#' || c == '!' -> out.append('\\').append(c)
                c == ' ' && (isKey || index == 0) -> out.append("\\ ")
                c.code < 0x20 || c.code > 0x7e -> out.append("\\u").append("%04x".format(c.code))
                else -> out.append(c)
            }
        }
        return out.toString()
    }
}
